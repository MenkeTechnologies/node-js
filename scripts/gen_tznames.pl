#!/usr/bin/env perl
# Transcribe ICU's en specific zone names into src/tznames_data.rs.
# Inputs are files from the ICU release-79.1 source tree (icu4c/source/data/):
#   perl scripts/gen_tznames.pl misc/metaZones.txt misc/timezoneTypes.txt \
#     zone/en.txt zone/root.txt misc/zoneinfo64.txt > src/tznames_data.rs
#   rustfmt --edition 2021 src/tznames_data.rs
use strict; use warnings; use utf8;
use Time::Local qw(timegm);
binmode STDOUT, ':utf8';
my ($mzf, $ttf, $enf) = @ARGV;
sub slurp { open my $f, '<:utf8', $_[0] or die "$_[0]: $!"; local $/; my $s = <$f>; $s =~ s/^\x{FEFF}//; $s }
sub section { my ($text, $name) = @_; $text =~ /^    \Q$name\E\{\n(.*?)^    \}\n/ms or die "no $name"; $1 }
sub epoch { my ($d) = @_; my ($y,$mo,$da,$h,$mi) = $d =~ /^(\d+)-(\d+)-(\d+) (\d+):(\d+)$/ or die $d; timegm(0,$mi,$h,$da,$mo-1,$y) }

# typeAlias/timezone: alias -> ICU canonical id.
my $tt = section(slurp($ttf), 'typeAlias');
my %alias;
while ($tt =~ /^            "([^"]+)"\{"([^"]+)"\}/mg) { (my $k = $1) =~ tr/:/\//; $alias{$k} = $2 }

# zoneinfo64 links (`UTC`, `GB`): a name that is not itself a CLDR id
# (typeMap/timezone) resolves to its link target, then through typeAlias.
my $zi = slurp($ARGV[4]);
$zi =~ /^ Names \{\n(.*?)^ \}/ms or die "no Names";
my @tznames = $1 =~ /"([^"]+)"/g;
my %cldr_id;
{
  my $tm = section(slurp($ttf), 'typeMap');
  while ($tm =~ /^            "([^"]+:[^"]+)"\{/mg) { (my $k = $1) =~ tr/:/\//; $cldr_id{$k} = 1 }
}
while ($zi =~ /^  \/\* (\S+) \*\/ :int \{ (\d+) \}/mg) {
  my ($link, $target) = ($1, $tznames[$2]);
  next if $cldr_id{$link};
  $alias{$link} //= $alias{$target} // $target;
}

# metazoneInfo: zone -> [(metazone, from, to)].
my $mi = section(slurp($mzf), 'metazoneInfo');
my %zones;
while ($mi =~ /^        "([^"]+)"\{\n(.*?)^        \}\n/msg) {
  (my $z = $1) =~ tr/:/\//;
  my $body = $2; my @r;
  while ($body =~ /^            \{\n(.*?)^            \}\n/msg) {
    my @f = $1 =~ /"([^"]*)"/g;
    my $from = defined $f[1] ? epoch($f[1]) : 'i64::MIN';
    my $to = defined $f[2] ? ($f[2] eq '9999-12-31 23:59' ? 'i64::MAX' : epoch($f[2])) : 'i64::MAX';
    push @r, [$f[0], $from, $to];
  }
  $zones{$z} = \@r;
}

# en "meta:X" specific names.
my $en = slurp($enf);
my %names;
while ($en =~ /^        "meta:([^"]+)"\{\n(.*?)^        \}\n/msg) {
  my ($mz, $body) = ($1, $2); my %n;
  while ($body =~ /^            (ls|ld|ss|sd)\{"([^"]*)"\}/mg) { $n{$1} = $2 }
  $names{$mz} = \%n if %n;
}

# Zone-specific names ("Etc:UTC"), en over root.
my %zn;
for my $src (slurp($ARGV[3]), $en) {
  while ($src =~ /^        "([A-Z][^"]*:[^"]+)"\{\n(.*?)^        \}\n/msg) {
    (my $z = $1) =~ tr/:/\//;
    my $body = $2;
    while ($body =~ /^            (ls|ld|ss|sd)\{"([^"]*)"\}/mg) { $zn{$z}{$1} = $2 }
  }
}

my $o = sub { defined $_[0] ? "Some(\"$_[0]\")" : 'None' };
print "// GENERATED by transcribing ICU release-79.1 (CLDR 49, the data node v26.12.1\n";
print "// ships): the aliases of `misc/timezoneTypes.txt` (typeAlias/timezone) and\n";
print "// `misc/zoneinfo64.txt` (links), the metazone history of `misc/metaZones.txt`\n";
print "// (metazoneInfo), en's metazone names (`zone/en.txt`, each `meta:` entry's\n";
print "// ls/ld/ss/sd) and the zone-specific names of `zone/en.txt` over\n";
print "// `zone/root.txt`. Times are UTC epoch seconds. Formatted by rustfmt; do not\n";
print "// edit by hand: regenerate with scripts/gen_tznames.pl.\n\n";
print "/// `(alias, ICU canonical id)`, sorted by alias.\n";
print "pub(crate) const ALIASES: &[(&str, &str)] = &[\n";
print "    (\"$_\", \"$alias{$_}\"),\n" for sort keys %alias;
print "];\n\n";
print "/// One span of a zone's metazone history: `(metazone, from, to)`, `[from, to)`.\n";
print "pub(crate) type MetazoneSpan = (&'static str, i64, i64);\n\n";
print "/// `(ICU canonical id, [span])`, sorted by id.\n";
print "pub(crate) const ZONE_METAZONES: &[(&str, &[MetazoneSpan])] = &[\n";
for my $z (sort keys %zones) {
  print "    (\n        \"$z\",\n        &[\n";
  print "            (\"$_->[0]\", $_->[1], $_->[2]),\n" for @{$zones{$z}};
  print "        ],\n    ),\n";
}
print "];\n\n";
print "/// `(metazone, [long standard, long daylight, short standard, short daylight])`,\n/// sorted by metazone.\n";
print "pub(crate) const METAZONE_NAMES: &[(&str, [Option<&str>; 4])] = &[\n";
for my $mz (sort keys %names) {
  my $n = $names{$mz};
  print "    (\n        \"$mz\",\n        [\n", map({ "            " . $o->($n->{$_}) . ",\n" } qw(ls ld ss sd)), "        ],\n    ),\n";
}
print "];\n\n";
print "/// `(ICU canonical id, [long standard, long daylight, short standard, short\n/// daylight])` for the zones named on their own, ahead of any metazone.\n";
print "pub(crate) const ZONE_NAMES: &[(&str, [Option<&str>; 4])] = &[\n";
for my $z (sort keys %zn) {
  my $n = $zn{$z};
  print "    (\n        \"$z\",\n        [\n", map({ "            " . $o->($n->{$_}) . ",\n" } qw(ls ld ss sd)), "        ],\n    ),\n";
}
print "];\n";
